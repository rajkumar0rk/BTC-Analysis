import {test,expect} from "@playwright/test";
import {readFileSync} from "node:fs";
test("quick rerun retains immutable experiments, compares, persists and restores",async({page})=>{
 test.setTimeout(180000);
 const o=JSON.parse(readFileSync("tests/browser-oracle.json","utf8"));
 await page.goto("/");await page.getByRole("button",{name:"Open local Python runner"}).click();
 await page.getByLabel("Historical CSV").setInputFiles({name:"fixture.csv",mimeType:"text/csv",buffer:Buffer.from(o.csv)});
 await page.getByText("Assume CSV times are candle opens; provenance and contract specs are unverified.").click();
 await page.getByLabel("Experiment name").fill("Baseline");
 await page.getByLabel("Local visual source").fill(JSON.stringify(o.graph));
 await page.getByRole("button",{name:"Run local Python",exact:true}).click();
 await expect(page.getByRole("heading",{name:"Local reference result"})).toBeVisible({timeout:125000});
 await page.getByRole("button",{name:"Save CSV on this device"}).click();
 await expect(page.getByText("Validated CSV saved on this device.",{exact:false})).toBeVisible();
 await page.getByLabel("Experiment name").fill("Candidate");
 await page.getByLabel("Local visual source").fill(JSON.stringify(o.changed_graph));
 await page.getByRole("button",{name:"Run local Python",exact:true}).click();
 await expect(page.getByRole("heading",{name:"Local reference result"})).toBeVisible({timeout:30000});
 await page.getByRole("button",{name:"Compare latest two runs"}).click();
 await expect(page.getByLabel("Comparison validity")).toContainText("Comparable:");
 await expect(page.getByRole("heading",{name:"Monthly P&L comparison"})).toBeVisible();
 await page.getByRole("button",{name:"Save experiment history on this device"}).click();
 await expect(page.getByText("Experiment history saved on this device.",{exact:false})).toBeVisible();
 await page.reload();await page.getByRole("button",{name:"Open local Python runner"}).click();
 const history=page.getByLabel("Local experiment history");
 await expect(history.getByRole("button",{name:"Restore inputs"})).toHaveCount(2);
 await history.getByRole("button",{name:"Restore inputs"}).first().click();
 await expect(page.getByText(/Inputs restored. Import the matching CSV/)).toBeVisible();
 await expect(page.getByRole("button",{name:"Run local Python",exact:true})).toBeDisabled();
 await page.getByRole("button",{name:"Load saved CSV",exact:true}).click();
 await expect(page.getByText("Saved CSV restored and checksum verified.",{exact:false})).toBeVisible();
 await page.getByText("Assume CSV times are candle opens; provenance and contract specs are unverified.").click();
 await page.getByLabel("initial_equity",{exact:true}).fill("200");
 await page.getByRole("button",{name:"Run local Python",exact:true}).click();
 await expect(page.getByRole("heading",{name:"Local reference result"})).toBeVisible({timeout:125000});
 await page.getByRole("button",{name:"Compare latest two runs"}).click();
 await expect(page.getByLabel("Comparison validity")).toContainText("improvement deltas suppressed");
 await page.getByRole("button",{name:"Clear experiment history",exact:true}).click();
 await page.getByRole("button",{name:"Confirm clear experiments"}).click();
 await expect(history.getByText("No completed experiments yet.")).toBeVisible();
 await page.reload();await page.getByRole("button",{name:"Open local Python runner"}).click();
 await expect(page.getByText("No completed experiments yet.")).toBeVisible();
});
